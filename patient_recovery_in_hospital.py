import pandas as pd
import numpy as np
from google.colab import files

# Loading the hospital dataset
df = pd.read_csv("hospital data analysis.csv")

print("======================================")
print(" HOSPITAL PATIENT RECOVERY ANALYSIS")
print("======================================")

while True:

    print("\n---------- MAIN MENU ----------")
    print("1. Total Patient Records")
    print("2. Patient Recovery Analysis")
    print("3. Medical Condition Analysis")
    print("4. Hospital Stay Analysis")
    print("5. Treatment Cost Analysis")
    print("6. Readmission Analysis")
    print("7. Patient Satisfaction Analysis")
    print("8. Search Patient")
    print("9. Generate Hospital Report")
    print("0. Exit")

    choice = input("\nEnter your choice: ")

    # 1. Total Patient Records
    if choice == "1":

        print("\nTOTAL PATIENT RECORDS")
        print("Total Patients:", len(df))
        print("Unique Patients:", df["Patient_ID"].nunique())
        print("Average Age:", round(df["Age"].mean(), 2))

    # 2. Patient Recovery Analysis
    elif choice == "2":

        print("\nPATIENT RECOVERY ANALYSIS")
        print(df["Outcome"].value_counts())

        recovered = (df["Outcome"] == "Recovered").sum()
        stable = (df["Outcome"] == "Stable").sum()

        print("Recovered Patients:", recovered)
        print("Stable Patients:", stable)

        recovery_percentage = (recovered / len(df)) * 100
        print("Recovery Percentage:", round(recovery_percentage, 2), "%")

    # 3. Medical Condition Analysis
    elif choice == "3":

        print("\nMEDICAL CONDITION ANALYSIS")
        print(df["Condition"].value_counts())

        print("Most Common Condition:",
              df["Condition"].mode()[0])

    # 4. Hospital Stay Analysis
    elif choice == "4":

        print("\nHOSPITAL STAY ANALYSIS")

        stay = np.array(df["Length_of_Stay"])

        print("Average Stay:", round(np.mean(stay), 2), "days")
        print("Maximum Stay:", np.max(stay), "days")
        print("Minimum Stay:", np.min(stay), "days")

    # 5. Treatment Cost Analysis
    elif choice == "5":

        print("\nTREATMENT COST ANALYSIS")

        cost = np.array(df["Cost"])

        print("Total Treatment Cost:", np.sum(cost))
        print("Average Treatment Cost:", round(np.mean(cost), 2))
        print("Maximum Cost:", np.max(cost))
        print("Minimum Cost:", np.min(cost))

    # 6. Readmission Analysis
    elif choice == "6":

        print("\nREADMISSION ANALYSIS")

        print(df["Readmission"].value_counts())

        yes = (df["Readmission"] == "Yes").sum()
        no = (df["Readmission"] == "No").sum()

        print("Readmitted Patients:", yes)
        print("Not Readmitted Patients:", no)

        percentage = (yes / len(df)) * 100
        print("Readmission Percentage:", round(percentage, 2), "%")

    # 7. Patient Satisfaction Analysis
    elif choice == "7":

        print("\nPATIENT SATISFACTION ANALYSIS")

        satisfaction = np.array(df["Satisfaction"])

        print("Average Satisfaction:", round(np.mean(satisfaction), 2))

        print("Highest Satisfaction:", np.max(satisfaction))
        print("Lowest Satisfaction:", np.min(satisfaction))

    # 8. Search Patient
    elif choice == "8":

        print("\nSEARCH PATIENT")

        patient_id = int(input("Enter Patient ID: "))

        patient = df[df["Patient_ID"] == patient_id]

        if len(patient) > 0:
            print(patient[[
                "Patient_ID", "Age", "Condition",
                "Procedure", "Cost", "Length_of_Stay",
                "Readmission", "Outcome", "Satisfaction"
            ]].to_string(index=False))
        else:
            print("Patient not found!")

    # 9. Generate Hospital Report
    elif choice == "9":

        recovered = (df["Outcome"] == "Recovered").sum()
        readmitted = (df["Readmission"] == "Yes").sum()

        report = open("Hospital_Report.txt", "w")

        report.write("HOSPITAL PATIENT RECOVERY REPORT\n")
        report.write("--------------------------------\n")
        report.write("Total Patients: " + str(len(df)) + "\n")
        report.write("Recovered Patients: " + str(recovered) + "\n")
        report.write("Stable Patients: " +
                     str((df["Outcome"] == "Stable").sum()) + "\n")
        report.write("Readmitted Patients: " + str(readmitted) + "\n")
        report.write("Average Hospital Stay: " +
                     str(round(df["Length_of_Stay"].mean(), 2)) + " days\n")
        report.write("Average Treatment Cost: " +
                     str(round(df["Cost"].mean(), 2)) + "\n")
        report.write("Average Satisfaction: " +
                     str(round(df["Satisfaction"].mean(), 2)) + "\n")

        report.close()

        print("Hospital report generated successfully!")

        files.download("Hospital_Report.txt")

    # 0. Exit
    elif choice == "0":

        print("Thank you for using the Hospital Recovery Analysis System!")
        break

    else:
        print("Invalid choice! Please enter a number from 0 to 9.")